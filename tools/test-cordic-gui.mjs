import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve('cordic.html')).href);
  assert.match(await page.locator('#result').textContent(), /^0\.577350/);
  assert.ok(Number.isFinite(Number(await page.locator('#bcd-result').textContent())));
  assert.match(await page.locator('#comparison-summary').textContent(), /10 Mantissenstellen/);
  await page.locator('#first-difference').click();
  assert.equal(await page.locator('#state-comparison tr').count(), 4);
  await page.locator('#last').click();
  assert.ok(await page.locator('#convergence .bcd-path').count() > 0);
  assert.ok(await page.locator('#arithmetic-difference .path').count() > 0);
  await page.locator('#step').fill('0');
  await page.locator('#next').click();
  assert.match(await page.locator('#position').textContent(), /^1 \/ /);
  await page.locator('#step').fill('20');
  assert.match(await page.locator('#position').textContent(), /^20 \/ /);
  await page.locator('#play').click();
  await page.waitForFunction(() => Number(document.querySelector('#step').value) > 20);
  await page.locator('#play').click();
  for (const fn of ['sin', 'cos', 'tan', 'atan', 'ln', 'log10', 'exp', 'pow10']) {
    await page.locator('#function').selectOption(fn);
    await page.locator('#input').fill('0.6');
    await page.locator('button[type=submit]').click();
    assert.equal(await page.locator('#error').isVisible(), false);
    assert.ok(Number.isFinite(Number(await page.locator('#result').textContent())));
    assert.ok(await page.locator('#convergence line').count() > 3);
  }
  await page.locator('#precision').selectOption('13');
  await page.locator('#function').selectOption('sin');
  await page.locator('#input').fill('45');
  await page.locator('button[type=submit]').click();
  const lastStep = Number(await page.locator('#step').getAttribute('max'));
  await page.locator('#step').fill(String(lastStep - 2));
  assert.equal(await page.locator('#phase').textContent(), 'Rotation');
  assert.equal(await page.locator('#geometry .normalization-path').count(), 0);
  const raw = await page.locator('#geometry [data-vector="double"]').evaluate(el => ({ x: Number(el.dataset.x), y: Number(el.dataset.y), cx: Number(el.getAttribute('cx')), cy: Number(el.getAttribute('cy')) }));
  assert.equal(raw.x, 1); assert.equal(raw.y, 1);
  const arc = await page.locator('#geometry .unit-circle').getAttribute('d');
  const radius = Number(arc.split('A')[1].trim().split(' ')[0]);
  assert.ok(Math.abs(Math.hypot(raw.cx - 70, 280 - raw.cy) / radius - Math.SQRT2) < 1e-12);
  assert.equal(await page.locator('#geometry .addition-path').count(), 1);
  await page.locator('#next').click();
  assert.equal(await page.locator('#phase').textContent(), 'Auswertung');
  assert.equal(await page.locator('#geometry .normalization-path').count(), 0);
  const evaluated = await page.locator('#geometry [data-vector="double"]').evaluate(el => ({ cx: Number(el.getAttribute('cx')), cy: Number(el.getAttribute('cy')) }));
  assert.ok(Math.abs(Math.hypot(evaluated.cx - 70, 280 - evaluated.cy) / radius - Math.SQRT2) < 1e-12);
  assert.equal(evaluated.cx, raw.cx); assert.equal(evaluated.cy, raw.cy);
  await page.locator('#last').click();
  assert.equal(await page.locator('#geometry [data-vector="double"]').getAttribute('data-x'), '1');
  assert.equal(await page.locator('#geometry [data-vector="double"]').getAttribute('data-y'), '1');
  await page.locator('#precision').selectOption('10');
  await page.locator('#function').selectOption('ln');
  await page.locator('#input').fill('7.3');
  await page.locator('button[type=submit]').click();
  await page.locator('#first-branch').click();
  assert.match(await page.locator('#alignment-note').textContent(), /nur/);
  await page.locator('#precision').selectOption('13');
  await page.locator('button[type=submit]').click();
  assert.match(await page.locator('#comparison-summary').textContent(), /13 Mantissenstellen/);
  await page.locator('#input').fill('-1');
  await page.locator('button[type=submit]').click();
  assert.match(await page.locator('#error').textContent(), /x > 0/);
  assert.equal(await page.locator('#visualization').isVisible(), false);
  await page.locator('#function').selectOption('tan');
  await page.locator('#input').fill('30');
  await page.locator('button[type=submit]').click();
  await page.locator('#protocol summary').click();
  await page.locator('#trace tr').nth(5).click();
  assert.match(await page.locator('#position').textContent(), /^5 \/ /);
  const download = page.waitForEvent('download');
  await page.locator('#export').click();
  assert.equal((await download).suggestedFilename(), 'cordic-tan.json');
  await page.locator('#last').click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#protocol summary').click();
  await page.screenshot({ path: '/tmp/cordic-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.screenshot({ path: '/tmp/cordic-desktop.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('CORDIC GUI: unnormalized vectors preserved through function extraction, dual arithmetic, branch alignment, controls, animation, all functions, errors, export and mobile layout passed.');
} finally { await browser.close(); }
